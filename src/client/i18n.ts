export type DictKey = keyof (typeof DICT)['en']

export function tr(locale: Locale, key: DictKey): string {
  return DICT[locale][key]
}

export function formatPhaseLabel(phase: TaskPhase, locale: Locale): string {
  switch (phase) {
    case 'needs_you':
      return locale === 'zh' ? '待处理' : 'Needs Attention'
    case 'active':
      return locale === 'zh' ? '在做' : 'In Progress'
    case 'on_hold':
      return locale === 'zh' ? '停住了' : 'Paused'
    case 'todo':
      return locale === 'zh' ? '没开始' : 'Not Started'
    case 'closed':
      return locale === 'zh' ? '已收尾' : 'Completed'
  }
}

export function formatPhaseSubPhaseLabel(
  phase: TaskPhase,
  subPhase: TaskSubPhase,
  locale: Locale,
): string {
  if (locale === 'zh') {
    if (phase === 'needs_you') {
      switch (subPhase) {
        case 'review':
          return '待你验收'
        case 'blocked':
          return '已受阻'
        case 'needs_input':
          return '待你回复'
        case 'permission_pending':
          return '待确认权限'
        case 'reminder_due':
          return '提醒到期'
        default:
          return '待处理'
      }
    }
    if (phase === 'active') return '在做'
    if (phase === 'on_hold') return subPhase === 'waiting' ? '等待中' : '停住了'
    if (phase === 'todo') {
      if (subPhase === 'backlog') return '备选池'
      if (subPhase === 'draft') return 'AI 草稿 · 待审'
      return '没开始'
    }
    if (phase === 'closed') return subPhase === 'cancelled' ? '已取消' : '已收尾'
  }
  if (phase === 'needs_you') {
    switch (subPhase) {
      case 'review':
        return 'Ready for Review'
      case 'blocked':
        return 'Blocked'
      case 'needs_input':
        return 'Needs Reply'
      case 'permission_pending':
        return 'Needs Permission'
      case 'reminder_due':
        return 'Reminder Due'
      default:
        return 'Needs Attention'
    }
  }
  if (phase === 'active') return 'In Progress'
  if (phase === 'on_hold') return subPhase === 'waiting' ? 'Waiting' : 'Paused'
  if (phase === 'todo') {
    if (subPhase === 'backlog') return 'Backlog'
    if (subPhase === 'draft') return 'AI Draft · Needs Review'
    return 'Not Started'
  }
  if (phase === 'closed') return subPhase === 'cancelled' ? 'Cancelled' : 'Completed'
  return phase
}

export function formatPriorityLabel(priority: TaskPriority, locale: Locale): string {
  switch (priority) {
    case 'urgent':
      return tr(locale, 'prioUrgent')
    case 'high':
      return tr(locale, 'prioHigh')
    case 'normal':
      return tr(locale, 'prioNormal')
    case 'low':
      return tr(locale, 'prioLow')
  }
}

